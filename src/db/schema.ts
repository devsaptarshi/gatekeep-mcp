import { sql } from "drizzle-orm";
import { integer, sqliteTable, text } from "drizzle-orm/sqlite-core";

/**
 * Detects "rug pulls": an upstream server changing a tool's definition
 * (description, input schema, annotations) after it was first seen. The
 * gateway hashes a tool's definition on every tools/list and compares it
 * against the pinned hash; a mismatch is surfaced, never silently accepted.
 */
export const toolPins = sqliteTable("tool_pins", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  serverId: text("server_id").notNull(),
  toolName: text("tool_name").notNull(),
  definitionHash: text("definition_hash").notNull(),
  status: text("status", { enum: ["pinned", "changed"] }).notNull().default("pinned"),
  firstSeenAt: text("first_seen_at").notNull().default(sql`(strftime('%Y-%m-%dT%H:%M:%fZ','now'))`),
});

/**
 * One row per exact call awaiting (or having received) a human decision.
 * `call_hash` is the unique key: it already encodes server/tool/arguments/
 * tool_definition_hash/principal/policy_version, so two different calls
 * never collide and the same call retried never creates a duplicate row.
 *
 * `canonical_args` is what actually gets forwarded to the upstream on
 * consume — never whatever arguments the agent sends when it retries after
 * approval. This is what closes the TOCTOU / argument-swap gap.
 */
export const approvals = sqliteTable("approvals", {
  id: text("id").primaryKey(), // ULID-ish, generated by the caller
  callHash: text("call_hash").notNull().unique(),
  serverId: text("server_id").notNull(),
  toolName: text("tool_name").notNull(),
  principal: text("principal").notNull(),
  canonicalArgs: text("canonical_args").notNull(), // JSON string
  reason: text("reason").notNull(),
  status: text("status", { enum: ["pending", "approved", "denied", "expired"] })
    .notNull()
    .default("pending"),
  decidedBy: text("decided_by"),
  createdAt: text("created_at").notNull().default(sql`(strftime('%Y-%m-%dT%H:%M:%fZ','now'))`),
  expiresAt: text("expires_at").notNull(),
  consumedAt: text("consumed_at"),
});

/**
 * Tamper-evident, hash-chained audit log. Every policy decision and every
 * approval lifecycle transition appends one row. `event_hash` is a SHA-256
 * over the row's own fields AND `prev_hash` (the previous row's
 * event_hash) — so editing or deleting any row, or reordering them, breaks
 * the chain from that point forward. `gatekeep verify` walks the whole
 * table and recomputes it; it must catch every edited row, not just the
 * most recent one.
 */
/**
 * Remembers risky events (e.g. "untrusted_read") within one gateway run,
 * so a flow rule can require human approval the first time a run tries to
 * follow an untrusted read with an external-send tool — even though
 * either action alone might be fine. See policy `flows` + PolicyEngine's
 * `tagsFor`/`flowsFor`.
 */
export const runTags = sqliteTable("run_tags", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  runId: text("run_id").notNull(),
  tag: text("tag").notNull(),
  sourceTool: text("source_tool").notNull(),
  seenAt: text("seen_at").notNull().default(sql`(strftime('%Y-%m-%dT%H:%M:%fZ','now'))`),
});

export const auditEvents = sqliteTable("audit_events", {
  seq: integer("seq").primaryKey({ autoIncrement: true }),
  runId: text("run_id").notNull(),
  event: text("event").notNull(),
  callHash: text("call_hash"),
  decision: text("decision"),
  prevHash: text("prev_hash").notNull(),
  eventHash: text("event_hash").notNull(),
  redactedPayload: text("redacted_payload").notNull(), // JSON string, secrets stripped before storage
  createdAt: text("created_at").notNull().default(sql`(strftime('%Y-%m-%dT%H:%M:%fZ','now'))`),
});
